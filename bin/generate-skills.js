#!/usr/bin/env node
// Generated packages are independent installations, not independently authored methods.
const fs = require('node:fs')
const path = require('node:path')
const { createHash } = require('node:crypto')
const catalog = require('./skill-catalog')
const { interfaceYaml } = require('./skill-ui')
const root = path.resolve(__dirname, '..')
const source = path.join(root, 'skills/fde/references')

function referencesFor(method, referenceRoot = source) {
  const known = new Set(fs.readdirSync(referenceRoot).filter(f => f.endsWith('.md')))
  const pending = [`${method}.md`, 'task-context.md']
  const found = new Set()
  while (pending.length) {
    const file = pending.pop()
    if (found.has(file)) continue
    if (!known.has(file)) throw new Error(`Missing canonical reference: ${file}`)
    found.add(file)
    const body = fs.readFileSync(path.join(referenceRoot, file), 'utf8')
    // Includes plain/backticked method links in older references as well as Markdown links.
    for (const match of body.matchAll(/(?<![\w-])([a-z][a-z-]*\.md)\b/g)) {
      if (known.has(match[1]) && !found.has(match[1])) pending.push(match[1])
    }
    for (const match of body.matchAll(/\]\(([^)]+\.md)(?:#[^)]*)?\)/g)) {
      if (/^(?:https?:|#)/.test(match[1])) continue
      const target = path.resolve(referenceRoot, match[1])
      if (path.dirname(target) !== referenceRoot || !known.has(path.basename(target))) {
        throw new Error(`Nonportable instruction link in ${file}: ${match[1]}`)
      }
    }
  }
  return [...found].sort()
}
const inputGuidance = {
  context: 'Work directly from the supplied permitted context. Standalone work does not require an engagement folder or initialization. Record filenames in the method are optional persistence destinations when no engagement is bound.',
  records: 'This task operates on existing engagement records. Use the local CLI and permitted sanitized packets; do not invent a portfolio or initialize records merely to complete the task. Report missing records or access as a limitation.',
  source: 'Source configuration and capability checks do not require an engagement record. Use available host tools and source documentation. Any later record staging or application follows the ingest method and its binding and confirmation requirements.',
  'record-write': 'Use permitted supplied material or available source tools to prepare a sourced proposal without requiring an engagement record. CLI staging and reconciliation use a bound engagement; applying updates requires the bound record and confirmation. Do not claim an unbound draft has been saved to engagement memory.',
}
function entrypoint(item) {
  const mode = item.inputMode || 'context'
  if (!Object.hasOwn(inputGuidance, mode)) throw new Error(`Invalid input mode: ${mode}`)
  return `---\nname: ${item.name}\ndescription: ${item.description}\n---\n\n# ${item.name}\n\n<!-- Generated by bin/generate-skills.js; edit the canonical references and catalog. -->\n\n## Purpose\n\n${item.result}\n\nBefore investigating or acting:\n1. Read [the task context contract](references/task-context.md).\n2. Read [the method](references/${item.method}.md).\n\nLoad further references only when the task needs them. Everything linked is included in this skill; no other skill pack is required.\n\n## Principles\n\n- ${inputGuidance[mode]}\n- If called by @fde, reuse its current sanitized packet and scope. Do not restart setup, discovery or questions already answered.\n- The task context contract controls persistence and authority in both modes. Preserve unknowns and distinguish implementation, verification, deployment and acceptance.\n- Use the customer's repository instructions and available tools. Report a missing capability or unrun check honestly; do not claim that installing a skill provisions infrastructure.\n`
}
function expectedFiles(item, referenceRoot = source) {
  const files = new Map([['SKILL.md', entrypoint(item)]])
  const ui = interfaceYaml(item.name, item.ui)
  if (ui) files.set('agents/openai.yaml', ui)
  for (const ref of referencesFor(item.method, referenceRoot)) files.set(`references/${ref}`, fs.readFileSync(path.join(referenceRoot, ref), 'utf8'))
  return files
}
const marker = '<!-- Generated by bin/generate-skills.js; edit the canonical references and catalog. -->'
const manifestName = '.fde-generated.json'
const digest = body => createHash('sha256').update(body).digest('hex')
const stat = file => {
  try { return fs.lstatSync(file) } catch (error) { if (error.code === 'ENOENT') return null; throw error }
}
function walk(dir, prefix = '') {
  const entries = []
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix + e.name
    if (e.isSymbolicLink() || (!e.isDirectory() && !e.isFile()) || (e.isFile() && fs.lstatSync(path.join(dir, e.name)).nlink > 1)) throw new Error(`Unsafe generated path: ${path.join(dir, e.name)}`)
    if (e.isDirectory()) {
      if (rel !== 'references' && rel !== 'agents') throw new Error(`Unowned generated directory: ${path.join(dir, e.name)}`)
      entries.push(...walk(path.join(dir, e.name), rel + '/'))
    } else entries.push(rel)
  }
  return entries
}
function generate(check = false, options = {}) {
  const skillRoot = path.join(options.root || root, 'skills')
  const referenceRoot = options.referenceRoot || source
  const items = options.catalog || catalog
  const wanted = new Map()
  for (const item of items) {
    if (!/^[a-z][a-z-]*$/.test(item.name) || item.name === 'fde' || item.name.startsWith('fde-') || wanted.has(item.name)) throw new Error(`Invalid generated skill name: ${item.name}`)
    wanted.set(item.name, expectedFiles(item, referenceRoot))
  }
  const rootStat = stat(skillRoot)
  if (rootStat && (!rootStat.isDirectory() || rootStat.isSymbolicLink())) throw new Error(`Unsafe skills root: ${skillRoot}`)
  const names = new Set([...wanted.keys(), ...(rootStat ? fs.readdirSync(skillRoot).filter(n => n !== 'fde' && /^[a-z][a-z-]*$/.test(n)) : [])])
  const errors = []
  const plans = []
  for (const name of names) {
    const dest = path.join(skillRoot, name)
    const expected = wanted.get(name) || new Map()
    const destStat = stat(dest)
    let owned = {}
    let actual = []
    if (destStat) {
      if (!destStat.isDirectory() || destStat.isSymbolicLink()) {
        if (wanted.has(name)) throw new Error(`Unsafe generated path: ${dest}`)
        continue
      }
      const entry = path.join(dest, 'SKILL.md')
      const entryStat = stat(entry)
      const isGenerated = entryStat && entryStat.isFile() && fs.readFileSync(entry, 'utf8').includes(marker)
      if (!isGenerated) {
        if (wanted.has(name) || stat(path.join(dest, manifestName))) throw new Error(`Unowned skill: ${name}`)
        continue
      }
      actual = walk(dest)
      if (actual.includes(manifestName)) {
        const manifest = JSON.parse(fs.readFileSync(path.join(dest, manifestName), 'utf8'))
        if (manifest.generator !== 'bin/generate-skills.js' || manifest.version !== 1 || !manifest.files || Array.isArray(manifest.files) || typeof manifest.files !== 'object') throw new Error(`Invalid ownership manifest: ${name}`)
        owned = manifest.files
        for (const [rel, hash] of Object.entries(owned)) {
          if (!/^(?:SKILL\.md|agents\/openai\.yaml|references\/[a-z][a-z-]*\.md)$/.test(rel) || !/^[a-f0-9]{64}$/.test(hash)) throw new Error(`Invalid ownership entry: ${name}/${rel}`)
        }
      } else {
        // Migrate 4.1.0 packages conservatively: only the marked entry and exact
        // canonical copies are known to belong to the generator.
        for (const rel of actual) {
          const body = fs.readFileSync(path.join(dest, rel))
          const canonical = path.join(referenceRoot, path.basename(rel))
          if (rel === 'SKILL.md' || (/^references\/[a-z][a-z-]*\.md$/.test(rel) && stat(canonical)?.isFile() && body.equals(fs.readFileSync(canonical)))) owned[rel] = digest(body)
        }
      }
      for (const rel of actual.filter(rel => rel !== manifestName)) {
        if (!Object.hasOwn(owned, rel)) throw new Error(`Unowned generated file: ${name}/${rel}`)
        if (!expected.has(rel) && digest(fs.readFileSync(path.join(dest, rel))) !== owned[rel]) throw new Error(`Modified obsolete generated file: ${name}/${rel}`)
      }
    }
    const output = new Map(expected)
    if (wanted.has(name)) output.set(manifestName, JSON.stringify({ generator: 'bin/generate-skills.js', version: 1, files: Object.fromEntries([...expected].map(([rel, body]) => [rel, digest(body)])) }, null, 2) + '\n')
    for (const rel of actual) if (!output.has(rel)) errors.push(`Obsolete generated file: ${name}/${rel}`)
    for (const [rel, body] of output) {
      if (!actual.includes(rel) || fs.readFileSync(path.join(dest, rel), 'utf8') !== body) errors.push(`Stale generated skill: ${name}/${rel}`)
    }
    plans.push({ dest, actual, output })
  }
  if (check) {
    if (errors.length) throw new Error(errors.join('\n'))
    return
  }
  // All ownership and path checks finish before any package is changed.
  for (const { dest, actual, output } of plans) {
    for (const rel of actual) if (!output.has(rel)) fs.unlinkSync(path.join(dest, rel))
    for (const [rel, body] of output) {
      fs.mkdirSync(path.dirname(path.join(dest, rel)), { recursive: true })
      fs.writeFileSync(path.join(dest, rel), body)
    }
    for (const directory of ['references', 'agents']) {
      const target = path.join(dest, directory)
      if (stat(target)?.isDirectory() && fs.readdirSync(target).length === 0) fs.rmdirSync(target)
    }
    if (!output.size) fs.rmdirSync(dest)
  }
}
module.exports = { referencesFor, expectedFiles, generate }
if (require.main === module) {
  try { generate(process.argv.includes('--check')); console.log('Skill packages match canonical methods.') }
  catch (error) { console.error(error.message); process.exitCode = 1 }
}
