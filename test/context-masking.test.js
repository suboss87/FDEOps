test('output protection handles split writes and multiline credentials', t => {
  const f = fixture(t), modulePath = path.resolve(__dirname, '../bin/lib/masking.js')
  const script = `const m=require(${JSON.stringify(modulePath)});m.protectOutput(m.createMasking(${JSON.stringify(path.join(f.dir, 'clients'))}));process.stdout.write('mara@');process.stdout.write('example.com');process.stderr.write('-----BEGIN PRIVATE KEY-----\\nSECRET_BODY\\n-----END PRIVATE KEY-----');`
  const result = spawnSync(process.execPath, ['-e', script], { env: f.env, encoding: 'utf8' })
  assert.equal(result.status, 0, result.stderr)
  assert.doesNotMatch(result.stdout + result.stderr, /mara@|example.com|SECRET_BODY/)
})
