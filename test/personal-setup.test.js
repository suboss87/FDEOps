test('quoted and backslash custom terms are masked before command diagnostics are serialized', t => {
  const f = fixture(t), term = 'Mara "Secret" Chen', other = 'Atlas\\East'
  fs.writeFileSync(f.terms, term + '\n' + other + '\n')
  assert.equal(f.save('single', 'daily', 'custom', f.terms).status, 0)
  assert.equal(f.run(['resume', '--init', 'client']).status, 0)
  for (const text of [term, other]) {
    for (const args of [['redact', text], ['log', 'risk', '--retire', text]]) {
      const out = f.run(args)
      assert.doesNotMatch(out.stdout + out.stderr, /Mara|Secret|Atlas/)
    }
  }
})
